export const TOUR_MESSAGES: Record<Locale, TourMessages> = { es, en };

export function tourMessages(locale: Locale): TourMessages {
  return TOUR_MESSAGES[locale] ?? es;
}

/** Sustituye `{var}` en los textos de `data`/`errors` (sin plurales: para eso hay llaves aparte). */
export function fillText(template: string, vars: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

